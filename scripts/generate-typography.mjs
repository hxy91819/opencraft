import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const registryPath = resolve(root, "packages/design-system/src/typography/typography.tokens.json");
const outputPath = resolve(root, "packages/design-system/src/typography/_generated.web.scss");
const registry = JSON.parse(await readFile(registryPath, "utf8"));
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const weight = (name) => registry.weights[name];
const roles = registry.platforms.web.roles;
const scales = registry.platforms.web.scales;

const lines = [
  "// DO NOT EDIT. Generated by scripts/generate-typography.mjs.",
  `$typography-role-names: (${Object.keys(roles).map(kebab).join(", ")});`,
  "",
  ":root {",
  `  --font-family-ui: ${registry.families.ui.web};`,
  `  --font-family-content: ${registry.families.content.web};`,
  `  --font-family-mono: ${registry.families.mono.web};`,
  "  --font-sans: var(--font-family-ui);",
  "  --font-mono: var(--font-family-mono);",
  ...Object.entries(registry.weights).map(([name, value]) => `  --font-weight-${name}: ${value};`),
  ...Object.entries(registry.tracking).map(([name, value]) => `  --font-tracking-${name}: ${value}em;`),
];

for (const [name, definition] of Object.entries(roles)) {
  const roleName = kebab(name);
  const scale = scales[definition.scale];
  lines.push(
    `  --typography-${roleName}-family: var(--font-family-${definition.family});`,
    `  --typography-${roleName}-size: ${scale.fontSize}px;`,
    `  --typography-${roleName}-line-height: ${scale.lineHeight}px;`,
    `  --typography-${roleName}-weight: ${weight(definition.weight)};`,
  );
}

lines.push(
  "  --font-text-lg-size: 18px;",
  "  --font-text-lg-line-height: 29px;",
  "  --font-text-md-size: 16px;",
  "  --font-text-md-line-height: 24px;",
  "  --font-text-sm-size: var(--typography-body-size);",
  "  --font-text-sm-line-height: var(--typography-body-line-height);",
  "  --font-text-xs-size: 12px;",
  "  --font-text-xs-line-height: 18px;",
  "  --font-text-2xs-size: 10px;",
  "  --font-text-2xs-line-height: 14px;",
  "  --codex-sidebar-font-size: var(--typography-navigation-action-size);",
  "  --codex-sidebar-line-height: var(--typography-navigation-action-line-height);",
  "  --codex-sidebar-meta-font-size: var(--typography-metadata-size);",
  "  --codex-sidebar-meta-line-height: var(--typography-metadata-line-height);",
  "}",
  "",
);

const generated = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated) {
    console.error("Typography Web adapter is stale. Run npm run generate:typography.");
    process.exit(1);
  }
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated ${outputPath}`);
}
